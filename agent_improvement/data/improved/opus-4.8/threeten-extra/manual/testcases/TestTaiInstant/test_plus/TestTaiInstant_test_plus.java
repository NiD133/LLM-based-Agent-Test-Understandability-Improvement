    /**
     * Adding a {@link Duration} adds the seconds and nanoseconds component-wise,
     * normalising any nanosecond carry/borrow into the seconds field.
     */
    @ParameterizedTest
    @MethodSource("data_plus")
    public void test_plus(long startSeconds, int startNanos, long durationSeconds, int durationNanos,
            long expectedSeconds, int expectedNanos) {
        TaiInstant result = TaiInstant.ofTaiSeconds(startSeconds, startNanos)
                .plus(Duration.ofSeconds(durationSeconds, durationNanos));

        assertEquals(expectedSeconds, result.getTaiSeconds());
        assertEquals(expectedNanos, result.getNano());
    }
