    @ParameterizedTest
    @MethodSource("data_untilCLD")
    public void test_until_CLD(int startYear, int startMonth, int startDay,
            int endYear, int endMonth, int endDay,
            int expectedYears, int expectedMonths, int expectedDays) {
        BritishCutoverDate start = BritishCutoverDate.of(startYear, startMonth, startDay);
        BritishCutoverDate end = BritishCutoverDate.of(endYear, endMonth, endDay);

        ChronoPeriod period = start.until(end);

        ChronoPeriod expectedPeriod =
                BritishCutoverChronology.INSTANCE.period(expectedYears, expectedMonths, expectedDays);
        assertEquals(expectedPeriod, period);
    }
