    @ParameterizedTest
    @MethodSource("data_untilCLD")
    public void test_until_CLD(
            int startYear,
            int startMonth,
            int startDay,
            int endYear,
            int endMonth,
            int endDay,
            int expectedYears,
            int expectedMonths,
            int expectedDays) {

        BritishCutoverDate startDate = BritishCutoverDate.of(startYear, startMonth, startDay);
        BritishCutoverDate endDate = BritishCutoverDate.of(endYear, endMonth, endDay);

        ChronoPeriod periodUntilEndDate = startDate.until(endDate);

        assertEquals(
                BritishCutoverChronology.INSTANCE.period(expectedYears, expectedMonths, expectedDays),
                periodUntilEndDate);
    }
