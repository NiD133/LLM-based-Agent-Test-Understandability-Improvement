    /**
     * Verifies the round-trip invariant: {@code a.plus(a.until(b))} must equal {@code b}.
     *
     * <p>The {@code expectedYears}, {@code expectedMonths}, and {@code expectedDays} parameters
     * are provided by the data source for use by a sibling test; this test does not assert them.
     */
    @ParameterizedTest
    @MethodSource("data_untilCLD")
    public void test_until_CLD_plus(
            int year1, int month1, int dom1,
            int year2, int month2, int dom2,
            int expectedYears, int expectedMonths, int expectedDays) {
        BritishCutoverDate a = BritishCutoverDate.of(year1, month1, dom1);
        BritishCutoverDate b = BritishCutoverDate.of(year2, month2, dom2);
        ChronoPeriod period = a.until(b);
        assertEquals(b, a.plus(period));
    }
